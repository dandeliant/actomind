// Generates sw-manifest.js: the list of files the service worker precaches for offline use + a content hash version.
// Usage: node tools/gen-sw-manifest.mjs   (also run by `npm run build:sw`)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIRS = ['css', 'js', 'vendor', 'icons'];
const TOP = ['index.html', 'manifest.webmanifest'];

function walk(dir) {
  const out = [];
  for (const f of fs.readdirSync(path.join(ROOT, dir))) {
    const rel = dir + '/' + f;
    const st = fs.statSync(path.join(ROOT, rel));
    if (st.isDirectory()) out.push(...walk(rel));
    else if (!/LICENSE|\.map$|\.md$/i.test(f)) out.push(rel);
  }
  return out;
}

export const FILES = [...TOP, ...DIRS.flatMap((d) => (fs.existsSync(path.join(ROOT, d)) ? walk(d) : []))].sort();

export function build() {
  const h = crypto.createHash('sha256');
  for (const f of FILES) h.update(f).update(fs.readFileSync(path.join(ROOT, f)));
  const version = h.digest('hex').slice(0, 12);
  const body = `// Generated by tools/gen-sw-manifest.mjs – do not edit by hand.\nself.ACTOMIND_VERSION = '${version}';\nself.ACTOMIND_FILES = ${JSON.stringify(['./', ...FILES], null, 1)};\n`;
  fs.writeFileSync(path.join(ROOT, 'sw-manifest.js'), body);
  return { version, count: FILES.length };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const r = build();
  console.log(`sw-manifest.js: ${r.count} files, version ${r.version}`);
}
